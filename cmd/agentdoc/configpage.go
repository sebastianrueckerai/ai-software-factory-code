package main

// The opencode-internal subagents' page: general and explore run inside
// opencode, their prompts the binary's own — no first call of ours exists
// to capture. The page shows the one thing of ours on their path: the
// agent block of the session config, verbatim, under its builder's
// provenance.

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/sebastianrueckerai/ai-software-factory-code/internal/agentdoc"
	"github.com/sebastianrueckerai/ai-software-factory-code/internal/factoryd"
)

// configPage renders the config-level page for the opencode-internal
// subagents from the agent block AgentDocAgentConfig answered. It answers
// the page and the rot findings, like page does.
func configPage(a Agent, sha, policyCommit string, syms *symbolTable, frag json.RawMessage) (string, []string) {
	d := &doc{agent: a, sha: sha, policy: policyCommit, syms: syms}
	var md strings.Builder
	fmt.Fprintf(&md, "<!-- agentdoc: id=%s family=%s -->\n\n# %s\n\n", a.ID, a.Family, a.ID)
	fmt.Fprintf(&md, "%s · runs: %s\n\n", a.Job, a.Runs)
	md.WriteString("Regenerated by `go run ./cmd/agentdoc`; no LLM runs. Code SHA `")
	md.WriteString(d.sha)
	md.WriteString("`, policy `")
	md.WriteString(d.policy)
	md.WriteString("`.\n\n")
	md.WriteString("No first call of ours exists to capture: the subagents' prompts are opencode's own, inside the binary (`")
	md.WriteString(factoryd.AgentDocOpencodeVersion)
	md.WriteString("`). What our side of their path sets is the `agent` block of the session config, verbatim below.\n\n")
	sp := agentdoc.Span{Name: "the agent block", Symbol: "buildOpencodeConfig", Kind: agentdoc.KindBuilder, Place: agentdoc.PlaceUser, Text: string(frag)}
	fmt.Fprintf(&md, "#### the agent block — %s\n\n%s · %d bytes\n\n", sp.Kind, d.provenance(sp), len(frag))
	f := fence(string(frag))
	fmt.Fprintf(&md, "%sjson\n%s\n%s\n\n", f, frag, f)
	md.WriteString(d.footer())
	return md.String(), d.failures
}
