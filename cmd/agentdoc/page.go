package main

// One agent's page: the first request part by part, each part a
// provenance line (symbol, permalink at the recorded SHA, bytes) and its
// verbatim text, long parts collapsed. The page renders no verdict —
// sizes, places and origins are all it says. Failures are rot findings;
// the tool prints them and refuses to ship the map.

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/sebastianrueckerai/ai-software-factory-code/internal/agentdoc"
)

// codeBase is the code repo's web home; permalinks point at the SHA the
// map was regenerated from.
const codeBase = "https://github.com/sebastianrueckerai/ai-software-factory-code"

// collapseOver is the byte size a part's verbatim text folds into a
// collapsed block at.
const collapseOver = 1024

// section is one message of one place, as a locatable string: plain
// content, or a part list joined in order.
type section struct {
	role  string
	place string
	text  string
}

type doc struct {
	agent    Agent
	sha      string
	policy   string
	syms     *symbolTable
	rec      agentdoc.Recorded
	body     agentdoc.Body
	failures []string
}

func (d *doc) fail(format string, args ...any) {
	d.failures = append(d.failures, fmt.Sprintf(format, args...))
}

// page renders a's captured request rec, labelled by spans, at code sha
// and policy commit. It answers the page and the rot findings; a caller
// with findings does not ship.
func page(a Agent, sha, policyCommit string, syms *symbolTable, rec agentdoc.Recorded, spans []agentdoc.Span) (string, []string) {
	d := &doc{agent: a, sha: sha, policy: policyCommit, syms: syms, rec: rec}
	b, err := agentdoc.ParseBody(rec.Raw)
	if err != nil {
		d.fail("%s: %v", a.ID, err)
		return d.header(0), d.failures
	}
	d.body = b
	var md strings.Builder
	md.WriteString(d.header(len(rec.Raw)))
	md.WriteString("## Where this agent sits\n\n```mermaid\n")
	md.WriteString(pageDiagram(d.agent.ID))
	md.WriteString("\n```\n\n")
	d.writeRequest(&md, spans)
	d.writeTools(&md, spans)
	md.WriteString(d.footer())
	return md.String(), d.failures
}

func (d *doc) header(requestBytes int) string {
	b := d.body
	var md strings.Builder
	fmt.Fprintf(&md, "<!-- agentdoc: id=%s family=%s -->\n\n# %s\n\n", d.agent.ID, d.agent.Family, d.agent.ID)
	fmt.Fprintf(&md, "%s · runs: %s\n\n", d.agent.Job, d.agent.Runs)
	if b, ok := blurbOf(d.agent.ID); ok {
		md.WriteString(b)
		md.WriteString("\n\n")
	}
	md.WriteString("Regenerated by `go run ./cmd/agentdoc`; no LLM runs. Code SHA `")
	md.WriteString(d.sha)
	md.WriteString("`, policy `")
	md.WriteString(d.policy)
	md.WriteString("`.\n\n")
	md.WriteString("**Fixture task, not live data.** The capture runs the real assembly on a fixed task against a fake gateway; nothing on this page is a live card's content.\n\n")
	format := "—"
	if b.ResponseFormat != "" {
		format = b.ResponseFormat
	}
	fmt.Fprintf(&md, "| model alias | max tokens | stream | response format | purpose | task | tools | request bytes |\n|---|---|---|---|---|---|---|---|\n")
	fmt.Fprintf(&md, "| `%s` | %d | %t | %s | `%s` | `%s` | %d | %d |\n\n",
		b.Model, b.MaxTokens, b.Stream, format, d.rec.Purpose, d.rec.Task, len(b.Tools), requestBytes)
	return md.String()
}

// sectionsOf answers body's messages as locatable sections, in wire order.
func sectionsOf(b agentdoc.Body) []section {
	var out []section
	for _, m := range b.Messages {
		s := section{role: m.Role, place: "user"}
		if m.Role == "system" {
			s.place = "system"
		}
		if m.Parts == nil {
			s.text = m.Content
		} else {
			var t strings.Builder
			for _, p := range m.Parts {
				if p.Text != "" {
					t.WriteString(p.Text)
				}
				if p.ImageURL != "" {
					t.WriteString(p.ImageURL)
				}
			}
			s.text = t.String()
		}
		// an assistant turn's tool calls are the wire's own bytes: they sit
		// in the section as they crossed it
		s.text += m.ToolCallText()
		out = append(out, s)
	}
	return out
}

// writeRequest renders the messages part by part, each part located.
func (d *doc) writeRequest(md *strings.Builder, spans []agentdoc.Span) {
	sections := sectionsOf(d.body)
	fmt.Fprintf(md, "## The first request\n\nVerbatim, part by part, top to bottom as it crossed the wire. Sizes are bytes of the decoded part.\n\n")
	for _, place := range []string{agentdoc.PlaceSystem, agentdoc.PlaceUser} {
		var placeSpans []agentdoc.Span
		for _, sp := range spans {
			if sp.Place == place {
				placeSpans = append(placeSpans, sp)
			}
		}
		var texts []string
		var idx []int
		for i, s := range sections {
			if s.place == place {
				texts = append(texts, s.text)
				idx = append(idx, i)
			}
		}
		if len(texts) == 0 {
			if len(placeSpans) > 0 {
				d.fail("%s: %s place: %d registered spans, but no such message crossed the wire", d.agent.ID, place, len(placeSpans))
			}
			continue
		}
		joined := strings.Join(texts, "\x00")
		claims, err := agentdoc.Locate(joined, placeSpans)
		if err != nil {
			d.fail("%s %s place: %v", d.agent.ID, place, err)
			continue
		}
		// map the joined offsets back onto the sections they belong to
		claimsOf := make([][]agentdoc.Claim, len(texts))
		at, who := 0, 0
		for _, c := range claims {
			// the \x00 between messages is this renderer's own join, not
			// a wire byte: it holds no provenance and claims none
			if strings.Trim(joined[c.Start:c.End], "\x00") == "" {
				continue
			}
			for who+1 < len(texts) && c.Start >= at+len(texts[who])+1 {
				at += len(texts[who]) + 1
				who++
			}
			if c.End > at+len(texts[who]) {
				name := c.Name
				if name == "" {
					name = "unlabelled bytes"
				}
				d.fail("%s %s place: span %s crosses a message boundary", d.agent.ID, place, name)
				continue
			}
			claimsOf[who] = append(claimsOf[who], rebase(c, at))
		}
		for n, i := range idx {
			d.writeSection(md, sections[i], claimsOf[n])
		}
	}
}

// writeSection renders one message and its located claims.
func (d *doc) writeSection(md *strings.Builder, s section, claims []agentdoc.Claim) {
	fmt.Fprintf(md, "### %s message\n\n", s.role)
	for _, c := range claims {
		d.writeClaim(md, s, c, 0)
	}
}

// writeClaim renders one located claim: a provenance line, then the
// verbatim text (collapsed when long), then nested spans named.
func (d *doc) writeClaim(md *strings.Builder, s section, c agentdoc.Claim, depth int) {
	indent := strings.Repeat("  ", depth)
	text := c.Text
	if c.Unlabelled {
		text = sliceOf(s, c)
		fmt.Fprintf(md, "%s#### unlabelled — %d bytes\n\n", indent, len(text))
		d.writeText(md, indent, text)
		d.fail("%s %s message: %d unlabelled bytes %q", d.agent.ID, s.role, len(text), clip(text))
		return
	}
	fmt.Fprintf(md, "%s#### %s — %s\n\n", indent, c.Name, c.Kind)
	fmt.Fprintf(md, "%s%s · %d bytes\n\n", indent, d.provenance(c.Span), len(text))
	d.writeText(md, indent, text)
	if len(c.Within) > 0 {
		var nested []string
		for _, w := range c.Within {
			nested = append(nested, fmt.Sprintf("%s — %s · %d bytes", w.Name, d.provenance(w.Span), len(w.Text)))
		}
		fmt.Fprintf(md, "%sContains: %s\n\n", indent, strings.Join(nested, "; "))
	}
}

// rebase moves a claim's offsets from the place's joined string onto the
// section it fell in.
func rebase(c agentdoc.Claim, at int) agentdoc.Claim {
	c.Start -= at
	c.End -= at
	for i, w := range c.Within {
		c.Within[i] = rebase(w, at)
	}
	return c
}

// sliceOf is the section text a claim covers.
func sliceOf(s section, c agentdoc.Claim) string {
	return s.text[c.Start:c.End]
}

// writeText writes text in a fenced block, collapsed past the fold.
func (d *doc) writeText(md *strings.Builder, indent, text string) {
	f := fence(text)
	if len(text) > collapseOver {
		fmt.Fprintf(md, "%s<details><summary>the verbatim text, %d bytes, collapsed</summary>\n\n", indent, len(text))
		fmt.Fprintf(md, "%s%stext\n%s\n%s\n\n", indent, f, text, f)
		fmt.Fprintf(md, "%s</details>\n\n", indent)
		return
	}
	fmt.Fprintf(md, "%s%stext\n%s\n%s\n\n", indent, f, text, f)
}

// provenance is the span's origin line: a Go builder's symbol as a
// permalink, or — the harness's own parts, a per-repo file, the capture
// script's answers — what it is, with no permalink to fake.
func (d *doc) provenance(sp agentdoc.Span) string {
	switch sp.Kind {
	case agentdoc.KindHarness:
		return "`" + sp.Symbol + "` · the harness's own"
	case agentdoc.KindFile:
		return "`" + sp.Symbol + "` · the repository's file the harness read"
	}
	if sp.Symbol == "" {
		return "`" + sp.Kind + "`"
	}
	rel, line, ok := d.syms.locate(d.agent.Pkg, sp.Symbol)
	if !ok {
		d.fail("%s: symbol %s of span %s resolves nowhere", d.agent.ID, sp.Symbol, sp.Name)
		return "`" + sp.Symbol + "`"
	}
	return fmt.Sprintf("[`%s`](%s/blob/%s/%s#L%d) · %s:%d", sp.Symbol, codeBase, d.sha, rel, line, rel, line)
}

// writeTools renders the offered tools, each with its provenance and the
// full schema JSON collapsed.
func (d *doc) writeTools(md *strings.Builder, spans []agentdoc.Span) {
	if len(d.body.Tools) == 0 {
		return
	}
	fmt.Fprintf(md, "## The offered tools\n\n%d tools. Names and descriptions in the open; each schema's full JSON collapsed under it.\n\n", len(d.body.Tools))
	byText := map[string]agentdoc.Span{}
	for _, sp := range spans {
		if sp.Place == agentdoc.PlaceTools {
			byText[sp.Text] = sp
		}
	}
	for _, t := range d.body.Tools {
		fmt.Fprintf(md, "### %s\n\n", t.Name)
		sp, ok := byText[string(t.Raw)]
		if !ok {
			d.fail("%s: tool %s is unlabelled", d.agent.ID, t.Name)
		} else {
			delete(byText, sp.Text)
			fmt.Fprintf(md, "%s · %d bytes\n\n", d.provenance(sp), len(t.Raw))
		}
		var schema struct {
			Function struct {
				Description string `json:"description"`
			} `json:"function"`
		}
		if err := json.Unmarshal(t.Raw, &schema); err != nil {
			d.fail("%s: tool %s's schema is unreadable: %v", d.agent.ID, t.Name, err)
		}
		if schema.Function.Description != "" {
			fmt.Fprintf(md, "%s\n\n", schema.Function.Description)
		}
		f := fence(string(t.Raw))
		fmt.Fprintf(md, "<details><summary>full schema JSON</summary>\n\n%sjson\n%s\n%s\n\n</details>\n\n", f, t.Raw, f)
	}
	for _, sp := range byText {
		d.fail("%s: span %s matches no tool on the wire", d.agent.ID, sp.Name)
	}
}

func (d *doc) footer() string {
	return fmt.Sprintf("The literal wire body sits in [`raw/%s.json`](raw/%s.json), byte for byte.\n", d.agent.ID, d.agent.ID)
}

// fence is a backtick fence the text cannot break.
func fence(text string) string {
	f := "```"
	for strings.Contains(text, f) {
		f += "`"
	}
	return f
}

// clip quotes a residue's first bytes for a failure line.
func clip(text string) string {
	if len(text) > 48 {
		return text[:48] + "…"
	}
	return text
}
